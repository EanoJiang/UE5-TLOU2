import unreal
at=unreal.AssetToolsHelpers.get_asset_tools()
m=at.create_asset("M_Test", "/Game/Test", unreal.Material, unreal.MaterialFactoryNew())
unreal.log("MAT "+str(m))
n=unreal.MaterialEditingLibrary.create_material_expression(m, unreal.MaterialExpressionVectorParameter, -400, 0)
unreal.log("NODE "+str(n))
unreal.log(str([x for x in dir(n) if not x.startswith("_")]))
try: n.set_editor_properties({"parameter_name":"Tint","default_value":unreal.LinearColor(0.2,0.3,0.4,1.0)}) ; unreal.log("SET OK")
except Exception as e: unreal.log("SET ERR "+str(e))
try: unreal.MaterialEditingLibrary.connect_material_property(n,"",unreal.MaterialProperty.MP_BASE_COLOR); unreal.log("CONNECT OK")
except Exception as e: unreal.log("CONNECT ERR "+str(e))
try: unreal.MaterialEditingLibrary.layout_material_expressions(m); unreal.log("LAYOUT OK")
except Exception as e: unreal.log("LAYOUT ERR "+str(e))
unreal.MaterialEditingLibrary.recompile_material(m)
unreal.EditorAssetLibrary.save_loaded_asset(m)
